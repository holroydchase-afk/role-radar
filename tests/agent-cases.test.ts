/* RR-AGENT v2 eval cases (AGV2-16 kept as AG-20, AGV2-17). Written BEFORE the code (red). No network.
 * AGV2-16: demo/agent/cases.json keeps 8 made-up cases (4 good, 4 bad fit), each with a reason, no real companies, no @.
 * AGV2-17: a case folder built from those 8 cases (slice 2, evals/job-hunt/) has, per case, graders/criteria.md that grades
 *   groundedness (no invented claims), fit judgement against the label, and usefulness, and names no arm.
 * Pinned layout: evals/job-hunt/job-hunt-<case id>/{prompt.md, graders/criteria.md}, the same shape eval-miss-cases.mjs writes for
 * qa-tdd and staff-pm. OPEN (QA-R2): eval-miss-cases.mjs only builds those two agents' cases, so "built by eval-miss-cases" needs a
 * job-hunt mode in studio-agents (same intake as B1); until then the folder is generated by a role-radar script and only checked here.
 */
import { test } from "node:test";
import assert from "node:assert/strict";
import { existsSync, readFileSync } from "node:fs";
import { join } from "node:path";
import { REPO } from "./agent-support.ts";

const doc = JSON.parse(readFileSync(join(REPO, "demo/agent/cases.json"), "utf8"));
const facts = JSON.parse(readFileSync(join(REPO, "demo/agent/facts.json"), "utf8")).facts.map((f: any) => f.id);
const cases: any[] = doc.cases;

test("AGV2-16 eight made-up cases: 4 good, 4 bad, each with a reason, ids unique, labeled demo", () => {
  assert.match(doc._label, /DEMO DATA|made up/i);
  assert.equal(cases.length, 8);
  assert.equal(cases.filter((c) => c.label === "good").length, 4);
  assert.equal(cases.filter((c) => c.label === "bad").length, 4);
  assert.equal(new Set(cases.map((c) => c.id)).size, 8);
  for (const c of cases) for (const k of ["id", "company", "title", "description", "reason"]) assert.ok(typeof c[k] === "string" && c[k].trim(), `${c.id}.${k}`);
});

test("AGV2-16 no @, links or phone numbers in the cases, and good cases cite only known demo fact ids", () => {
  const raw = readFileSync(join(REPO, "demo/agent/cases.json"), "utf8");
  assert.ok(!raw.includes("@") && !/https?:\/\/|www\./i.test(raw) && !/\(?\b\d{3}\)?[-. ]\d{3}[-. ]\d{4}\b/.test(raw));
  for (const c of cases) for (const f of c.factIds ?? []) assert.ok(facts.includes(f), `${c.id} cites ${f}`);
});

const folder = (id: string) => join(REPO, "evals", "job-hunt", `job-hunt-${id}`);

test("AGV2-17 every one of the 8 cases has a prompt.md and graders/criteria.md", () => {
  for (const c of cases) {
    assert.ok(existsSync(join(folder(c.id), "prompt.md")), `${c.id}: prompt.md`);
    assert.ok(existsSync(join(folder(c.id), "graders", "criteria.md")), `${c.id}: graders/criteria.md`);
  }
});

test("AGV2-17 criteria.md grades groundedness, fit judgement against the label, and usefulness", () => {
  for (const c of cases) {
    const p = join(folder(c.id), "graders", "criteria.md");
    assert.ok(existsSync(p), `${c.id}: criteria.md missing`);
    const t = readFileSync(p, "utf8");
    assert.match(t, /ground|invent/i, `${c.id}: groundedness (no invented claims)`);
    assert.match(t, /invent|not in the facts|no claim/i, `${c.id}: says what counts as invented`);
    assert.match(t, /\bfit\b/i, `${c.id}: fit judgement`);
    assert.match(t, new RegExp(`\\b${c.label}\\b`, "i"), `${c.id}: names its ${c.label} label`);
    assert.match(t, /useful/i, `${c.id}: usefulness`);
    assert.match(t, /PASS/);
    assert.match(t, /FAIL/);
  }
});

test("AGV2-17 criteria.md and prompt.md name no arm (blind grading): no agent, plain, baseline, run.ts, tool loop or arm labels", () => {
  const leak = /\barm\b|with-only|without-agent|baseline|plain claude|plain session|\bthe agent\b|job-hunt agent|run\.ts|tool loop|subagent|control group|\bA\/B\b/i;
  for (const c of cases) for (const f of [join("graders", "criteria.md"), "prompt.md"]) {
    const p = join(folder(c.id), f);
    assert.ok(existsSync(p), `${c.id}/${f} missing`);
    const m = leak.exec(readFileSync(p, "utf8"));
    assert.equal(m, null, `${c.id}/${f} names an arm: ${m?.[0]}`);
  }
});

test("AGV2-17 each criteria.md carries its own case's reason, not another's", () => {
  for (const c of cases) {
    const p = join(folder(c.id), "graders", "criteria.md");
    assert.ok(existsSync(p), `${c.id}: criteria.md missing`);
    const t = readFileSync(p, "utf8");
    assert.ok(t.includes(c.reason) || t.includes(c.company), `${c.id}: mentions its reason or company`);
    for (const o of cases) if (o.id !== c.id) assert.ok(!t.includes(o.company), `${c.id} names ${o.company}`);
  }
});
